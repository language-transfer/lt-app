const planPreloadedTracks = (course, indices, metadata) => {
  const seen = new Set();
  return indices.map((index) => {
    if (!Number.isInteger(index) || index < 0 || seen.has(index)) {
      throw new Error(`Invalid preloaded lesson index ${index} for ${course}`);
    }
    seen.add(index);
    const lesson = metadata.lessons[index];
    if (!lesson?.variants?.lq) {
      throw new Error(`Missing preloaded lesson ${index} for ${course}`);
    }
    if (!["video/mp4", "audio/mp4"].includes(lesson.variants.lq.mimeType)) {
      throw new Error(`Unsupported preloaded format for ${course} lesson ${index}`);
    }
    return { course, index, pointer: lesson.variants.lq };
  });
};

const renderPreloadedAssets = (tracks) => {
  const lines = tracks.map(
    ({ course, index }) =>
      `  ${JSON.stringify(`${course}:${index}`)}: require(${JSON.stringify(`./audio/${course}-${index}.m4a`)}),`
  );
  return `// Generated by scripts/prepare-preloaded-content.mjs.\nmodule.exports = {\n${lines.join("\n")}\n};\n`;
};

module.exports = { planPreloadedTracks, renderPreloadedAssets };
